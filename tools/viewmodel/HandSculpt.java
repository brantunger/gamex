    /** The glove's body: one surface from inside the cuff, over the wrist and the heel, to the knuckles. */
    private void palm() {
        // Each station: centre x, y, z, radius along the hand's width, radius through its thickness.
        double[][] stations = {
            station(along(0.050), 0.0295, 0.0210),
            station(along(0.022), 0.0278, 0.0198),
            station(WRIST, 0.0292, 0.0208),
            {0.0105, -0.0600, 0.1340, 0.0352, 0.0222},
            {0.0105, -0.0605, 0.1200, 0.0378, 0.0235},
            {0.0140, -0.0605, 0.1070, 0.0392, 0.0215},
            {0.0258, -0.0605, 0.0935, 0.0396, 0.0145},
            {0.0268, -0.0600, 0.0780, 0.0394, 0.0126},
            {0.0268, -0.0592, 0.0650, 0.0388, 0.0118},
            {0.0252, -0.0588, 0.0585, 0.0365, 0.0098},
        };
        List<double[]> rings = smooth(stations, 4);
        Part part = new Part("palm", "glove");
        int segments = 20;
        for (double[] ring : rings) part.ring(ringPoints(rings, ring, UP, segments, null));
        part.closeStart();
        part.roundEnd(rings.get(rings.size() - 1), rings.get(rings.size() - 2), 0.004, 3);
        emit(part, true);
    }

    /** A point with its two radii, as a station of a tube. */
    private static double[] station(double[] centre, double wide, double thick) {
        return new double[] {centre[0], centre[1], centre[2], wide, thick};
    }

    private static double fingerWidthTaper(double u) {
        return 1.0 - 0.24 * u * u;
    }

    private static double fingerThicknessTaper(double u) {
        return 1.0 - 0.38 * u * u;
    }

    /**
     * The path of a finger that wraps the grip at a height: right side, across the front strap, left side. The path
     * keeps the finger's tapered thickness away from the grip, so that its inner surface presses smoothly onto the
     * grip round to a staggered distal pad.
     * @param thick the finger's base radius through its thickness
     * @param tipBehind distance behind the front strap reached by the last cylinder station on the left panel
     */
    private static double[][] wrappingPath(double height, double thick, double tipBehind) {
        double leftTaper6 = fingerThicknessTaper(6.0 / 8.0);
        double leftTaper7 = fingerThicknessTaper(7.0 / 8.0);
        double leftTaper8 = fingerThicknessTaper(1.0);
        return new double[][] {
            onGrip(0.0305, height, 0.0315),
            onGrip(0.0156 + thick * fingerThicknessTaper(1.0 / 8.0), height, 0.0130),
            onGrip(0.0142 + thick * fingerThicknessTaper(2.0 / 8.0), height, -0.0030),
            onGrip(0.0095 + thick * fingerThicknessTaper(3.0 / 8.0), height, -thick * fingerThicknessTaper(3.0 / 8.0)),
            onGrip(0.0040, height, -thick * fingerThicknessTaper(4.0 / 8.0) - 0.0002),
            onGrip(-0.0118, height, -thick * fingerThicknessTaper(5.0 / 8.0)),
            onGrip(-0.0132 - thick * leftTaper6, height, -0.0035),
            onGrip(-0.0140 - thick * leftTaper7, height, 0.0125),
            onGrip(-0.0136 - thick * leftTaper8, height, tipBehind),
        };
    }

    /** The path of the index finger: along the right of the frame, bending onto the trigger face. */
    private static double[][] indexPath() {
        return new double[][] {
            onGrip(0.0305, -0.041, 0.0315),
            {0.0248, -0.0305, 0.0390},
            {0.0230, -0.0285, 0.0160},
            {0.0218, -0.0274, -0.0060},
            {0.0162, -0.0272, -0.0182},
            {0.0060, -0.0274, -0.0220},
            {-0.0035, -0.0278, -0.0222},
        };
    }

    /**
     * A finger: one tube along a path, pinched at its two creases, with an asymmetric tapered pad tip.
     * @param creases where the two creases are, as fractions of the path's length
     * @param pressBias inward shift of the fingertip dome so the palmar pad stays flush while the outer nail tapers
     * @param tipReach reach of the tapered fingertip cap beyond the final ring
     */
    private void finger(String name, double[][] path, double wide, double thick, double[] creases,
                        double[] pressBias, double tipReach) {
        double[][] stations = new double[path.length][];
        for (int i = 0; i < path.length; i++) {
            double u = i / (path.length - 1.0);
            stations[i] = station(path[i], wide * fingerWidthTaper(u), thick * fingerThicknessTaper(u));
        }
        List<double[]> rings = smooth(stations, 4);
        double length = 0.0;
        double[] travelled = new double[rings.size()];
        for (int i = 1; i < rings.size(); i++) {
            length += distance(rings.get(i - 1), rings.get(i));
            travelled[i] = length;
        }
        Part part = new Part(name, "glove");
        for (int i = 0; i < rings.size(); i++) {
            double[] ring = rings.get(i).clone();
            double fraction = travelled[i] / length;
            // A crease pinches the tube; the knuckle on either side of it swells a little.
            double scale = 1.0;
            for (double crease : creases) {
                double away = (fraction - crease) / 0.028;
                scale *= 1.0 - 0.20 * StrictMath.exp(-away * away) + 0.06 * StrictMath.exp(-(away * away) / 9.0);
            }
            ring[3] *= scale;
            ring[4] *= scale;
            part.ring(ringPoints(rings, rings.get(i), GRIP_AXIS, 12, ring));
        }
        part.closeStart();
        part.roundEnd(rings.get(rings.size() - 1), rings.get(rings.size() - 2), tipReach, 4, pressBias);
        emit(part, true);
    }

    /** The thumb: tucked smoothly below the beavertail web and tapering along the left of the frame. */
    private void thumb() {
        double[][] stations = {
            {-0.0020, -0.0500, 0.1160, 0.0175, 0.0155},
            {-0.0130, -0.0405, 0.0980, 0.0158, 0.0138},
            {-0.0205, -0.0275, 0.0780, 0.0132, 0.0118},
            {-0.0234, -0.0185, 0.0570, 0.0118, 0.0102},
            {-0.0240, -0.0158, 0.0370, 0.0112, 0.0092},
            {-0.0234, -0.0148, 0.0190, 0.0104, 0.0080},
            {-0.0226, -0.0146, 0.0078, 0.0096, 0.0072},
        };
        List<double[]> rings = smooth(stations, 4);
        Part part = new Part("thumb", "glove");
        double length = 0.0;
        double[] travelled = new double[rings.size()];
        for (int i = 1; i < rings.size(); i++) {
            length += distance(rings.get(i - 1), rings.get(i));
            travelled[i] = length;
        }
        for (int i = 0; i < rings.size(); i++) {
            double[] ring = rings.get(i).clone();
            double away = (travelled[i] / length - 0.62) / 0.035;
            double scale = 1.0 - 0.11 * StrictMath.exp(-away * away) + 0.05 * StrictMath.exp(-(away * away) / 9.0);
            ring[3] *= scale;
            ring[4] *= scale;
            part.ring(ringPoints(rings, rings.get(i), UP, 14, ring));
        }
        part.closeStart();
        part.roundEnd(rings.get(rings.size() - 1), rings.get(rings.size() - 2), 0.0092, 4,
            new double[] {0.0018, -0.0006, 0.0});
        emit(part, true);
    }

    /** A low padded dome over each knuckle of the back of the hand: together, the knuckle ridge. */
    private void knucklePads(double[] wrappingHeights) {
        double[] heights = {-0.041, wrappingHeights[0], wrappingHeights[1], wrappingHeights[2]};
        double[] archX = {0.0338, 0.0365, 0.0370, 0.0348};
        for (int i = 0; i < heights.length; i++) {
            double[] knuckle = onGrip(archX[i], heights[i], 0.0300);
            Part part = new Part("knuckle_pad_" + i, "pads");
            int bands = 5;
            int segments = 10;
            // An ellipsoid with its poles along x: thin contoured dorsal armor along the knuckle ridge.
            for (int band = 1; band < bands; band++) {
                double latitude = -StrictMath.PI / 2.0 + band * StrictMath.PI / bands;
                double[][] ring = new double[segments][];
                for (int s = 0; s < segments; s++) {
                    double longitude = (s + 0.5) * 2.0 * StrictMath.PI / segments;
                    ring[s] = new double[] {
                        knuckle[0] + 0.0048 * StrictMath.sin(latitude),
                        knuckle[1] + 0.0082 * StrictMath.cos(latitude) * StrictMath.cos(longitude),
                        knuckle[2] + 0.0110 * StrictMath.cos(latitude) * StrictMath.sin(longitude),
                    };
                }
                part.ring(ring);
            }
            part.closeStartAt(new double[] {knuckle[0] - 0.0048, knuckle[1], knuckle[2]});
            part.closeEndAt(new double[] {knuckle[0] + 0.0048, knuckle[1], knuckle[2]});
            emit(part, false);
        }
    }

    /** The cuff of the glove, a stiffer band standing proud of the wrist, with a strap round it. */
    private void cuff() {
        double[][] stations = {
            station(along(0.0360), 0.0310, 0.0226),
            station(along(0.0385), 0.0334, 0.0248),
            station(along(0.0560), 0.0340, 0.0254),
            station(along(0.0735), 0.0346, 0.0260),
            station(along(0.0760), 0.0322, 0.0238),
        };
        tube("cuff", "cuff", stations, 20);
        double[][] strap = {
            station(along(0.0500), 0.0340, 0.0254),
            station(along(0.0512), 0.0356, 0.0270),
            station(along(0.0628), 0.0358, 0.0272),
            station(along(0.0640), 0.0340, 0.0254),
        };
        tube("cuff_strap", "strap", strap, 20);
    }

    /** A tube with a ring at each station, flat at both ends. */
    private void tube(String name, String material, double[][] stations, int segments) {
        List<double[]> rings = new ArrayList<>();
        for (double[] station : stations) rings.add(station);
        Part part = new Part(name, material);
        for (double[] ring : rings) part.ring(ringPoints(rings, ring, UP, segments, null));
        part.closeStart();
        part.closeEnd();
        emit(part, false);
    }

    /** The sleeve: looser than the arm inside it, gathered behind the cuff, draped in slow folds along the forearm. */
    private void sleeve() {
        int rings = 26;
        int segments = 24;
        double from = 0.0700;
        double to = 0.5200;
        List<double[]> stations = new ArrayList<>();
        for (int i = 0; i < rings; i++) {
            // More rings near the cuff, where the fabric gathers.
            double u = StrictMath.pow(i / (rings - 1.0), 1.6);
            double[] centre = along(from + (to - from) * u);
            // The fabric hangs a little below the arm's axis.
            centre[1] -= 0.004 * StrictMath.sin(StrictMath.PI * StrictMath.min(1.0, u * 2.5));
            double grow = 1.0 + 0.36 * u;
            double gather = 1.0 + 0.09 * StrictMath.exp(-StrictMath.pow((u - 0.04) / 0.035, 2.0))
                - 0.06 * StrictMath.exp(-u / 0.007);
            stations.add(new double[] {centre[0], centre[1], centre[2], 0.0372 * grow * gather,
                0.0290 * grow * gather, u});
        }
        Part part = new Part("sleeve", "sleeve");
        for (double[] station : stations) {
            double u = station[5];
            double[][] ring = ringPoints(stations, station, UP, segments, null);
            double[] centre = {station[0], station[1], station[2]};
            for (int s = 0; s < segments; s++) {
                double angle = (s + 0.5) * 2.0 * StrictMath.PI / segments;
                // Clean, low-frequency longitudinal fabric drape folds without high-frequency rippling.
                double fold = 0.055 * StrictMath.sin(2.0 * angle + 4.5 * u + 0.5)
                    + 0.042 * StrictMath.sin(3.0 * angle - 7.5 * u + 1.1)
                    + 0.025 * StrictMath.sin(4.0 * angle + 9.0 * u) * StrictMath.exp(-u / 0.30);
                for (int axis = 0; axis < 3; axis++) {
                    ring[s][axis] = centre[axis] + (ring[s][axis] - centre[axis]) * (1.0 + fold);
                }
            }
            part.ring(ring);
        }
        part.closeStart();
        part.closeEnd();
        emit(part, false);
    }

    // ---- Skinning. ----

    /** @return the point of the forearm's axis at a distance from the wrist. */
    private static double[] along(double distance) {
        return new double[] {WRIST[0] + ARM[0] * distance, WRIST[1] + ARM[1] * distance, WRIST[2] + ARM[2] * distance};
    }

    /** @return the z of the front of the grip at a height, following the grip's rake. */
    private static double frontStrap(double y) {
        return 0.022 + (-0.018 - y) * (0.050 - 0.022) / (0.105 - 0.018);
    }

    /** @return a point of a finger that meets the front strap at a height and lies a distance behind it. */
    private static double[] onGrip(double x, double height, double behind) {
        return new double[] {x, height + FINGER_SLOPE * behind, frontStrap(height) + behind};
    }

    /**
     * Runs a smooth curve (a Catmull-Rom spline) through stations, interpolating their radii with it.
     * @param steps the number of rings per span between two stations
     */
    private static List<double[]> smooth(double[][] stations, int steps) {
        List<double[]> rings = new ArrayList<>();
        int last = stations.length - 1;
        for (int span = 0; span < last; span++) {
            double[] p0 = stations[StrictMath.max(0, span - 1)];
            double[] p1 = stations[span];
            double[] p2 = stations[span + 1];
            double[] p3 = stations[StrictMath.min(last, span + 2)];
            for (int step = 0; step < steps; step++) {
                double t = step / (double) steps;
                rings.add(spline(p0, p1, p2, p3, t));
            }
        }
        rings.add(stations[last].clone());
        return rings;
    }

    private static double[] spline(double[] p0, double[] p1, double[] p2, double[] p3, double t) {
        double[] out = new double[p1.length];
        double t2 = t * t;
        double t3 = t2 * t;
        for (int i = 0; i < out.length; i++) {
            out[i] = 0.5 * ((2.0 * p1[i]) + (-p0[i] + p2[i]) * t
                + (2.0 * p0[i] - 5.0 * p1[i] + 4.0 * p2[i] - p3[i]) * t2
                + (-p0[i] + 3.0 * p1[i] - 3.0 * p2[i] + p3[i]) * t3);
        }
        return out;
    }

    /**
     * Places the corners of one cross-section of a tube.
     * @param rings every ring centre of the tube, to take the tube's direction from
     * @param ring the ring to place
     * @param wideHint the direction the cross-section's wide radius follows, as nearly as the tube's direction allows
     * @param radii a ring whose radii to use instead of the ring's own, or null
     */
    private static double[][] ringPoints(List<double[]> rings, double[] ring, double[] wideHint, int segments,
                                         double[] radii) {
        int index = rings.indexOf(ring);
        double[] before = rings.get(StrictMath.max(0, index - 1));
        double[] after = rings.get(StrictMath.min(rings.size() - 1, index + 1));
        double[] tangent = normalise(new double[] {after[0] - before[0], after[1] - before[1], after[2] - before[2]});
        double dot = wideHint[0] * tangent[0] + wideHint[1] * tangent[1] + wideHint[2] * tangent[2];
        double[] wide = normalise(new double[] {wideHint[0] - dot * tangent[0], wideHint[1] - dot * tangent[1],
            wideHint[2] - dot * tangent[2]});
        // thick = tangent x wide, so that turning from wide towards thick is counter-clockwise seen from ahead.
        double[] thick = cross(tangent, wide);
        double wideRadius = radii != null ? radii[3] : ring[3];
        double thickRadius = radii != null ? radii[4] : ring[4];
        double[][] points = new double[segments][3];
        for (int s = 0; s < segments; s++) {
            double angle = (s + 0.5) * 2.0 * StrictMath.PI / segments;
            double alongWide = wideRadius * StrictMath.cos(angle);
            double alongThick = thickRadius * StrictMath.sin(angle);
            for (int axis = 0; axis < 3; axis++) {
                points[s][axis] = ring[axis] + alongWide * wide[axis] + alongThick * thick[axis];
            }
        }
        return points;
    }

    /** One part of the model: a stack of rings joined into a tube, closed at both ends. */
    private static final class Part {
        final String name;
        final String material;
        final List<double[]> vertices = new ArrayList<>();
        final List<int[]> faces = new ArrayList<>();
        private final List<int[]> ringIndices = new ArrayList<>();

        Part(String name, String material) {
            this.name = name;
            this.material = material;
        }

        /** Adds a ring and joins it to the ring before it. Rings run counter-clockwise seen from ahead. */
        void ring(double[][] points) {
            int[] indices = new int[points.length];
            for (int i = 0; i < points.length; i++) {
                indices[i] = vertices.size();
                vertices.add(points[i].clone());
            }
            if (!ringIndices.isEmpty()) {
                int[] low = ringIndices.get(ringIndices.size() - 1);
                for (int i = 0; i < indices.length; i++) {
                    int next = (i + 1) % indices.length;
                    faces.add(new int[] {indices[i], low[i], low[next], indices[next]});
                }
            }
            ringIndices.add(indices);
        }

        /** Closes the first ring with a fan round its centre. */
        void closeStart() {
            closeStartAt(centreOf(ringIndices.get(0)));
        }

        void closeStartAt(double[] point) {
            int[] ring = ringIndices.get(0);
            int centre = vertices.size();
            vertices.add(point.clone());
            for (int i = 0; i < ring.length; i++) faces.add(new int[] {centre, ring[(i + 1) % ring.length], ring[i]});
        }

        /** Closes the last ring with a fan round its centre. */
        void closeEnd() {
            closeEndAt(centreOf(ringIndices.get(ringIndices.size() - 1)));
        }

        void closeEndAt(double[] point) {
            int[] ring = ringIndices.get(ringIndices.size() - 1);
            int centre = vertices.size();
            vertices.add(point.clone());
            for (int i = 0; i < ring.length; i++) faces.add(new int[] {centre, ring[i], ring[(i + 1) % ring.length]});
        }

        /**
         * Rounds off the far end: shrinking rings that carry on past the last ring by a reach, then a pole.
         * @param last the centre of the last ring
         * @param previous the centre of the ring before it, which gives the direction to carry on in
         */
        void roundEnd(double[] last, double[] previous, double reach, int steps) {
            roundEnd(last, previous, reach, steps, new double[] {0.0, 0.0, 0.0});
        }

        /**
         * Rounds off the far end with an optional inward bias so palmar pads stay pressed flat against the weapon
         * while the dorsal nail bed tapers towards the pad.
         */
        void roundEnd(double[] last, double[] previous, double reach, int steps, double[] pressBias) {
            double[] ahead = normalise(new double[] {last[0] - previous[0], last[1] - previous[1],
                last[2] - previous[2]});
            int[] base = ringIndices.get(ringIndices.size() - 1);
            double[] centre = centreOf(base);
            double[][] rim = new double[base.length][];
            for (int i = 0; i < base.length; i++) rim[i] = vertices.get(base[i]);
            for (int step = 1; step < steps; step++) {
                double angle = step * StrictMath.PI / 2.0 / steps;
                double cos = StrictMath.cos(angle);
                double sin = StrictMath.sin(angle);
                double biasScale = sin * sin;
                double[][] points = new double[base.length][3];
                for (int i = 0; i < base.length; i++) {
                    for (int axis = 0; axis < 3; axis++) {
                        points[i][axis] = centre[axis] + (rim[i][axis] - centre[axis]) * cos
                            + ahead[axis] * reach * sin + pressBias[axis] * biasScale;
                    }
                }
                ring(points);
            }
            closeEndAt(new double[] {
                centre[0] + ahead[0] * reach + pressBias[0],
                centre[1] + ahead[1] * reach + pressBias[1],
                centre[2] + ahead[2] * reach + pressBias[2],
            });
        }

        private double[] centreOf(int[] ring) {
            double[] centre = new double[3];
            for (int index : ring) {
                for (int axis = 0; axis < 3; axis++) centre[axis] += vertices.get(index)[axis] / ring.length;
            }
            return centre;
        }
    }

    // ---- Fitting to the pistol, and output. ----

    /**
     * Fits a part to the pistol if asked, smooths its normals and appends it to the file. Fitting pushes the part's
     * vertices out of the pistol, then uncrosses the rings that cross, whether on a tight bend or because of the push,
     * and pushes again.
     */
    private void emit(Part part, boolean fitToPistol) {
        if (fitToPistol) {
            // The ring centres are taken before the push, which moves one side of a ring and so its centre.
            double[][] centres = new double[part.ringIndices.size()][];
            for (int ring = 0; ring < centres.length; ring++) centres[ring] = part.centreOf(part.ringIndices.get(ring));
            for (double[] vertex : part.vertices) pushOutOfPistol(vertex);
            uncrossRings(part, centres);
        }
        // A smooth normal is the sum of the normals of the faces round a vertex, each weighted by its area.
        double[][] normals = new double[part.vertices.size()][3];
        for (int[] face : part.faces) {
            for (int i = 1; i < face.length - 1; i++) {
                double[] a = part.vertices.get(face[0]);
                double[] b = part.vertices.get(face[i]);
                double[] c = part.vertices.get(face[i + 1]);
                double[] normal = cross(new double[] {b[0] - a[0], b[1] - a[1], b[2] - a[2]},
                    new double[] {c[0] - a[0], c[1] - a[1], c[2] - a[2]});
                for (int corner : new int[] {face[0], face[i], face[i + 1]}) {
                    for (int axis = 0; axis < 3; axis++) normals[corner][axis] += normal[axis];
                }
            }
        }
        obj.append("g ").append(part.name).append('\n');
        obj.append("usemtl ").append(part.material).append('\n');
        for (double[] vertex : part.vertices) {
            obj.append(String.format(Locale.ROOT, "v %.6f %.6f %.6f%n", vertex[0], vertex[1], vertex[2])
                .replace("\r", ""));
        }
        for (double[] normal : normals) {
            double[] unit = normalise(normal);
            obj.append(String.format(Locale.ROOT, "vn %.5f %.5f %.5f%n", unit[0], unit[1], unit[2])
                .replace("\r", ""));
        }
        for (int[] face : part.faces) {
            obj.append('f');
            for (int corner : face) {
                int index = vertexCount + corner + 1;
                obj.append(' ').append(index).append("//").append(index);
            }
            obj.append('\n');
        }
        vertexCount += part.vertices.size();
        faceCount += part.faces.size();
    }

    /** The solids of the pistol that the glove must stay out of: each a (y, z) outline and a half-width in x. */
    private static final double[][] PISTOL_OUTLINES = {GRIP_OUTLINE, FRAME_OUTLINE, SLIDE_OUTLINE, BEAVERTAIL_OUTLINE,
        PLATE_OUTLINE};
    private static final double[] PISTOL_HALF_WIDTHS = {GRIP_HALF_WIDTH, FRAME_HALF_WIDTH, SLIDE_HALF_WIDTH,
        BEAVERTAIL_HALF_WIDTH, PLATE_HALF_WIDTH};

    /**
     * Moves a point that lies inside the pistol to just outside it. The pistol's solids touch one another, so the
     * nearest way out of one may lead straight into the next; the point takes the nearest way out that ends clear of
     * every solid.
     */
    private static void pushOutOfPistol(double[] point) {
        for (int pass = 0; pass < 6; pass++) {
            int solid = containing(point, CLEARANCE * 0.5);
            if (solid < 0) return;
            double[][] exits = exits(point, PISTOL_OUTLINES[solid], PISTOL_HALF_WIDTHS[solid]);
            double[] chosen = exits[0];
            for (double[] exit : exits) {
                if (containing(exit, CLEARANCE * 0.5) < 0) {
                    chosen = exit;
                    break;
                }
            }
            point[0] = chosen[0];
            point[1] = chosen[1];
            point[2] = chosen[2];
        }
    }

    /** @return the index of a pistol solid that the point is inside of, or within a margin of, or -1. */
    private static int containing(double[] point, double margin) {
        for (int solid = 0; solid < PISTOL_OUTLINES.length; solid++) {
            if (depth(point, PISTOL_OUTLINES[solid], PISTOL_HALF_WIDTHS[solid]) > -margin) return solid;
        }
        return -1;
    }

    /**
     * @return how deep a point is inside a prism: the distance to its nearest face, or a negative number when the
     *     point is outside. The prism is a convex outline of (y, z) pairs extruded to a half-width either side of
     *     x = 0.
     */
    private static double depth(double[] point, double[] outline, double halfWidth) {
        double depth = halfWidth - StrictMath.abs(point[0]);
        int corners = outline.length / 2;
        double sign = turning(outline);
        for (int i = 0; i < corners && depth > -1.0; i++) {
            int next = (i + 1) % corners;
            double edgeY = outline[next * 2] - outline[i * 2];
            double edgeZ = outline[next * 2 + 1] - outline[i * 2 + 1];
            double length = StrictMath.sqrt(edgeY * edgeY + edgeZ * edgeZ);
            double outside = ((point[1] - outline[i * 2]) * sign * edgeZ
                - (point[2] - outline[i * 2 + 1]) * sign * edgeY) / length;
            depth = StrictMath.min(depth, -outside);
        }
        return depth;
    }

    /** @return the places just outside each face of a prism that a point inside it can be moved to, nearest first. */
    private static double[][] exits(double[] point, double[] outline, double halfWidth) {
        int corners = outline.length / 2;
        double sign = turning(outline);
        List<double[]> exits = new ArrayList<>();
        double side = point[0] >= 0.0 ? 1.0 : -1.0;
        // Each exit carries the distance moved as a fourth number, to sort by.
        exits.add(new double[] {side * (halfWidth + CLEARANCE), point[1], point[2],
            halfWidth + CLEARANCE - StrictMath.abs(point[0])});
        for (int i = 0; i < corners; i++) {
            int next = (i + 1) % corners;
            double edgeY = outline[next * 2] - outline[i * 2];
            double edgeZ = outline[next * 2 + 1] - outline[i * 2 + 1];
            double length = StrictMath.sqrt(edgeY * edgeY + edgeZ * edgeZ);
            // The outward normal of the edge, in (y, z).
            double normalY = sign * edgeZ / length;
            double normalZ = -sign * edgeY / length;
            double outside = (point[1] - outline[i * 2]) * normalY + (point[2] - outline[i * 2 + 1]) * normalZ;
            double move = CLEARANCE - outside;
            exits.add(new double[] {point[0], point[1] + normalY * move, point[2] + normalZ * move, move});
        }
        exits.sort((a, b) -> Double.compare(a[3], b[3]));
        return exits.toArray(new double[0][]);
    }

    /** @return 1 if an outline of (y, z) pairs runs counter-clockwise, -1 if clockwise. */
    private static double turning(double[] outline) {
        int corners = outline.length / 2;
        double area = 0.0;
        for (int i = 0; i < corners; i++) {
            int next = (i + 1) % corners;
            area += outline[i * 2] * outline[next * 2 + 1] - outline[next * 2] * outline[i * 2 + 1];
        }
        return area > 0.0 ? 1.0 : -1.0;
    }

    /**
     * Slides ring corners apart until every corner of a ring lies ahead of the same corner of the ring before it, by
     * at least {@link #RING_GAP} of the distance between the two ring centres, measured along the line between those
     * centres. Rings cross on the inside of a tight bend, and where the push out of the pistol moves one ring further
     * than the next; {@link Part#ring} joins corner i of one ring to corner i of the other, so the quad between two
     * crossed corners folds or faces inwards. On the palm only the later corner moves, forwards; on every other part
     * the two corners share the move. A move may take a corner back into the pistol, so the push runs again after
     * every sweep that moved one, until a sweep moves none.
     * @param centres the ring centres as they were before the push
     */
    private static void uncrossRings(Part part, double[][] centres) {
        boolean bothMove = !part.name.equals("palm");
        for (int sweep = 0; sweep < UNCROSS_SWEEPS; sweep++) {
            boolean moved = false;
            for (int ring = 0; ring + 1 < centres.length; ring++) {
                int[] low = part.ringIndices.get(ring);
                int[] high = part.ringIndices.get(ring + 1);
                double[] ahead = {centres[ring + 1][0] - centres[ring][0], centres[ring + 1][1] - centres[ring][1],
                    centres[ring + 1][2] - centres[ring][2]};
                double length = StrictMath.sqrt(ahead[0] * ahead[0] + ahead[1] * ahead[1] + ahead[2] * ahead[2]);
                if (length < 1e-9) continue;
                for (int axis = 0; axis < 3; axis++) ahead[axis] /= length;
                double gap = RING_GAP * length;
                for (int i = 0; i < low.length; i++) {
                    double[] a = part.vertices.get(low[i]);
                    double[] b = part.vertices.get(high[i]);
                    double lead = (b[0] - a[0]) * ahead[0] + (b[1] - a[1]) * ahead[1] + (b[2] - a[2]) * ahead[2];
                    if (lead >= gap - 1e-9) continue;
                    moved = true;
                    double shortfall = gap - lead;
                    for (int axis = 0; axis < 3; axis++) {
                        if (bothMove) {
                            a[axis] -= ahead[axis] * shortfall * 0.5;
                            b[axis] += ahead[axis] * shortfall * 0.5;
                        } else {
                            b[axis] += ahead[axis] * shortfall;
                        }
                    }
                }
            }
            if (!moved) return;
            for (double[] vertex : part.vertices) pushOutOfPistol(vertex);
        }
        throw new IllegalStateException("The rings of " + part.name + " are still crossed after " + UNCROSS_SWEEPS
            + " sweeps");
    }

    private static double distance(double[] a, double[] b) {
        double dx = a[0] - b[0];
        double dy = a[1] - b[1];
        double dz = a[2] - b[2];
        return StrictMath.sqrt(dx * dx + dy * dy + dz * dz);
    }

    private static double[] cross(double[] a, double[] b) {
        return new double[] {a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]};
    }

    private static double[] normalise(double[] v) {
        double length = StrictMath.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
        if (length < 1e-12) return new double[] {0.0, 1.0, 0.0};
        return new double[] {v[0] / length, v[1] / length, v[2] / length};
    }
