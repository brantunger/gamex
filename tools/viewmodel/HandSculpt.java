    /** The centre of the wrist: behind the grip, level with the middle of the palm. */
    private static final double[] WRIST = {0.012, -0.058, 0.150};
    /** The unit direction of the forearm from the wrist: back, a little to the right and down. */
    private static final double[] ARM = {0.157, -0.299, 0.941};
    /** The direction down the raked grip, which is the long axis of every finger's cross-section. */
    private static final double[] GRIP_AXIS = normalise(new double[] {0.0, -0.087, 0.028});
    /** How much lower a point of a finger lies per unit it lies further back: fingers cross the grip squarely. */
    private static final double FINGER_SLOPE = 0.32;
    private static final double[] UP = {0.0, 1.0, 0.0};

    private final StringBuilder obj = new StringBuilder();
    private int vertexCount;
    private int faceCount;

    public static void main(String[] args) throws IOException {
        if (args.length != 1) {
            System.err.println("usage: java tools/viewmodel/HandSculpt.java <output.obj>");
            System.exit(2);
        }
        HandSculpt sculpt = new HandSculpt();
        sculpt.build();
        Path out = Paths.get(args[0]);
        if (out.getParent() != null) Files.createDirectories(out.getParent());
        Files.write(out, sculpt.obj.toString().getBytes(StandardCharsets.UTF_8));
        System.out.println("Wrote " + out + ": " + sculpt.vertexCount + " vertices, " + sculpt.faceCount + " faces");
    }

    private void build() {
        obj.append("# The first-person hand, wrist, cuff and sleeve of gamex.\n");
        obj.append("# Generated by tools/viewmodel/HandSculpt.java; edit the generator, not this file.\n");
        obj.append("# Gun space: barrel along -z, y up, x to the shooter's right. Materials: glove, pads, cuff,\n");
        obj.append("# strap, sleeve.\n");
        palm();
        finger("index_finger", indexPath(), 0.0086, 0.0080, new double[] {0.36, 0.70},
            new double[] {0.0, -0.0010, 0.0018}, 0.0058);
        double[] heights = {-0.058, -0.0765, -0.095};
        double[] sizes = {1.0, 0.96, 0.86};
        double[] tipsBehind = {0.0332, 0.0302, 0.0276};
        String[] names = {"middle_finger", "ring_finger", "little_finger"};
        for (int i = 0; i < 3; i++) {
            double size = sizes[i];
            double thick = 0.0076 * size;
            finger(names[i], wrappingPath(heights[i], thick, tipsBehind[i]), 0.0090 * size, thick,
                new double[] {0.36, 0.68}, new double[] {0.0018 * size, 0.0, 0.0}, 0.0068 * size);
        }
        thumb();
        knucklePads(heights);
        cuff();
        sleeve();
    }

