import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

/**
 * Builds the first-person pistol and writes it as a Wavefront OBJ file.
 *
 * <p>Run it from the repository root with a JDK and nothing else:
 * <pre>java tools/viewmodel/PistolSculpt.java assets/models/viewmodel-pistol.obj</pre>
 *
 * <p>Gun space: the barrel points along negative z, y is up and x is to the shooter's right; the origin is the middle
 * of the underside of the slide. Lengths are roughly metres. Each solid is a closed convex prism written as its own
 * OBJ group ({@code g}) with one material ({@code usemtl}). No vertex normals are written: faces are flat, so the
 * game's OBJ loader computes each triangle's unit normal from its winding.
 *
 * <p>Solids whose name begins with {@code slide} belong to the animated slide group.
 */
public final class PistolSculpt {

    private static final float MUZZLE_X = 0f;
    private static final float MUZZLE_Y = 0.0125f;
    private static final float MUZZLE_Z = -0.111f;

    private static final String GUNMETAL = "gunmetal";
    private static final String GUNMETAL_TOP = "gunmetal_top";
    private static final String DARK_METAL = "dark_metal";
    private static final String STEEL = "steel";
    private static final String BORE = "bore";
    private static final String BRASS = "brass";
    private static final String SIGHT_DOT = "sight_dot";
    private static final String POLYMER = "polymer";
    private static final String POLYMER_DARK = "polymer_dark";
    private static final String STIPPLE = "stipple";

    private static final int AXIS_X = 0;
    private static final int AXIS_Z = 2;

    private final StringBuilder obj = new StringBuilder();
    private int vertexCount;
    private int faceCount;
    private int groupCount;

    public static void main(String[] args) throws IOException {
        if (args.length != 1) {
            System.err.println("usage: java tools/viewmodel/PistolSculpt.java <output.obj>");
            System.exit(2);
        }
        PistolSculpt sculpt = new PistolSculpt();
        sculpt.build();
        Path out = Paths.get(args[0]);
        if (out.getParent() != null) Files.createDirectories(out.getParent());
        Files.write(out, sculpt.obj.toString().getBytes(StandardCharsets.UTF_8));
        System.out.println("Wrote " + out + ": " + sculpt.groupCount + " groups, "
            + sculpt.vertexCount + " vertices, " + sculpt.faceCount + " faces");
    }

    private void build() {
        obj.append("# The first-person pistol of gamex.\n");
        obj.append("# Generated by tools/viewmodel/PistolSculpt.java; edit the generator, not this file.\n");
        obj.append("# Gun space: barrel along -z, y up, x to the shooter's right.\n");
        buildSlide();
        buildFrame();
        buildGrip();
    }

    private void buildSlide() {
        // The slide in two bands: flat flanks with a chamfered underside, and a top whose edges are bevelled twice.
        prism("slide", AXIS_Z, new float[] {
            -0.0125f, 0f, 0.0125f, 0f, 0.014f, 0.002f, 0.014f, 0.017f, -0.014f, 0.017f, -0.014f, 0.002f
        }, -0.105f, 0.082f, GUNMETAL);
        prism("slide top", AXIS_Z, new float[] {
            -0.014f, 0.017f, 0.014f, 0.017f, 0.0125f, 0.0225f, 0.009f, 0.0262f, 0.005f, 0.0275f,
            -0.005f, 0.0275f, -0.009f, 0.0262f, -0.0125f, 0.0225f
        }, -0.105f, 0.082f, GUNMETAL_TOP);
        // Grip serrations at the rear and a shorter set at the front, standing a little proud of both flanks.
        for (int i = 0; i < 7; i++) {
            float z = 0.034f + i * 0.0065f;
            box("slide serration " + i, -0.0147f, 0.0147f, 0.003f, 0.0165f, z, z + 0.003f, DARK_METAL);
        }
        for (int i = 0; i < 4; i++) {
            float z = -0.094f + i * 0.0065f;
            box("slide front serration " + i, -0.0147f, 0.0147f, 0.003f, 0.0165f, z, z + 0.003f, DARK_METAL);
        }
        box("slide top groove", -0.003f, 0.003f, 0.0270f, 0.0281f, -0.086f, 0.060f, DARK_METAL);
        // A ramped front sight with a brass bead, and a notched rear sight with two pale dots.
        prism("slide front sight", AXIS_X, new float[] {
            0.0275f, -0.102f, 0.0275f, -0.090f, 0.0345f, -0.090f, 0.0345f, -0.094f
        }, -0.0022f, 0.0022f, DARK_METAL);
        box("slide front sight bead", -0.0013f, 0.0013f, 0.0305f, 0.0338f, -0.0900f, -0.0894f, BRASS);
        box("slide rear sight base", -0.0105f, 0.0105f, 0.0275f, 0.0305f, 0.0655f, 0.0795f, DARK_METAL);
        box("slide rear sight left", -0.0105f, -0.0033f, 0.0305f, 0.0362f, 0.0655f, 0.0795f, DARK_METAL);
        box("slide rear sight right", 0.0033f, 0.0105f, 0.0305f, 0.0362f, 0.0655f, 0.0795f, DARK_METAL);
        box("slide rear sight dot left", -0.0083f, -0.0055f, 0.0320f, 0.0348f, 0.0795f, 0.0800f, SIGHT_DOT);
        box("slide rear sight dot right", 0.0055f, 0.0083f, 0.0320f, 0.0348f, 0.0795f, 0.0800f, SIGHT_DOT);
        box("slide ejection port", 0.006f, 0.0143f, 0.011f, 0.0172f, -0.030f, 0.004f, DARK_METAL);
        box("slide back plate", -0.006f, 0.006f, 0.005f, 0.019f, 0.082f, 0.0827f, DARK_METAL);
    }

    private void buildFrame() {
        // The barrel stays put when the slide moves, so it shows when the slide is back.
        prism("barrel", AXIS_Z, ring(MUZZLE_X, MUZZLE_Y, 0.0078f, 8), -0.110f, 0.010f, STEEL);
        prism("bore", AXIS_Z, ring(MUZZLE_X, MUZZLE_Y, 0.0046f, 8), MUZZLE_Z, -0.110f, BORE);
        // Side profiles are (y, z) pairs, extruded across x. The polymer frame's nose is cut back underneath.
        prism("frame", AXIS_X, new float[] {
            0f, -0.092f, 0f, 0.082f, -0.018f, 0.082f, -0.018f, -0.080f, -0.009f, -0.092f
        }, -0.013f, 0.013f, POLYMER);
        for (int i = 0; i < 3; i++) {
            float z = -0.078f + i * 0.012f;
            box("rail slot " + i, -0.009f, 0.009f, -0.0215f, -0.018f, z, z + 0.007f, POLYMER_DARK);
        }
        box("stop lever", -0.0148f, -0.013f, -0.008f, -0.003f, -0.036f, -0.006f, DARK_METAL);
        prism("magazine release", AXIS_X, ring(-0.027f, 0.027f, 0.0032f, 8), -0.0152f, -0.013f, DARK_METAL);
        // The trigger guard is a bar bent round a rounded front corner: one short solid per bend.
        float[] outer = {-0.018f, -0.043f, -0.036f, -0.044f, -0.046f, -0.037f, -0.050f, -0.025f, -0.050f, 0.010f,
            -0.045f, 0.027f};
        float[] inner = {-0.018f, -0.039f, -0.034f, -0.040f, -0.042f, -0.034f, -0.0455f, -0.024f, -0.0455f, 0.009f,
            -0.041f, 0.024f};
        for (int i = 0; i < 5; i++) {
            prism("trigger guard " + i, AXIS_X, new float[] {
                inner[i * 2], inner[i * 2 + 1], inner[i * 2 + 2], inner[i * 2 + 3],
                outer[i * 2 + 2], outer[i * 2 + 3], outer[i * 2], outer[i * 2 + 1]
            }, -0.0055f, 0.0055f, POLYMER);
        }
        // A curved trigger in two pieces.
        prism("trigger", AXIS_X, new float[] {
            -0.018f, -0.013f, -0.018f, -0.007f, -0.028f, -0.004f, -0.028f, -0.009f
        }, -0.003f, 0.003f, DARK_METAL);
        prism("trigger tip", AXIS_X, new float[] {
            -0.028f, -0.009f, -0.028f, -0.004f, -0.037f, -0.0055f, -0.037f, -0.0095f
        }, -0.003f, 0.003f, DARK_METAL);
        // A rounded spur hammer and a beavertail that curls down over the hand.
        prism("hammer", AXIS_X, new float[] {
            0.002f, 0.082f, 0.014f, 0.084f, 0.019f, 0.090f, 0.017f, 0.095f, 0.008f, 0.092f, 0.002f, 0.088f
        }, -0.004f, 0.004f, DARK_METAL);
        prism("beavertail", AXIS_X, new float[] {
            -0.004f, 0.080f, -0.004f, 0.094f, -0.007f, 0.100f, -0.011f, 0.102f, -0.016f, 0.098f, -0.018f, 0.082f
        }, -0.011f, 0.011f, POLYMER);
    }

    private void buildGrip() {
        // The grip is raked back, with a back strap that swells into the palm.
        prism("grip", AXIS_X, new float[] {
            -0.018f, 0.022f, -0.018f, 0.082f, -0.045f, 0.093f, -0.075f, 0.104f, -0.105f, 0.110f, -0.105f, 0.050f
        }, -0.013f, 0.013f, POLYMER);
        prism("magazine plate", AXIS_X, new float[] {
            -0.105f, 0.046f, -0.105f, 0.113f, -0.112f, 0.115f, -0.112f, 0.048f
        }, -0.0145f, 0.0145f, POLYMER_DARK);
        // Stippling: a chequered field of small studs on both sides, following the rake.
        for (int row = 0; row < 11; row++) {
            float y = -0.030f - row * 0.0066f;
            for (int column = 0; column < 6; column++) {
                float z = frontStrap(y) + 0.008f + column * 0.0068f;
                String material = (row + column) % 2 == 0 ? STIPPLE : POLYMER_DARK;
                box("stipple left " + row + "/" + column, -0.0146f, -0.013f, y - 0.0036f, y, z, z + 0.0036f,
                    material);
                box("stipple right " + row + "/" + column, 0.013f, 0.0146f, y - 0.0036f, y, z, z + 0.0036f,
                    material);
            }
        }
    }

    /** @return the z of the front of the grip at a height, following the grip's rake. */
    private static float frontStrap(float y) {
        return 0.022f + (-0.018f - y) * (0.050f - 0.022f) / (0.105f - 0.018f);
    }

    /** @return the corners of a regular polygon, as an outline for {@link #prism}. */
    private static float[] ring(float centreU, float centreV, float radius, int sides) {
        float[] outline = new float[sides * 2];
        for (int i = 0; i < sides; i++) {
            double angle = (i + 0.5) * 2.0 * Math.PI / sides;
            outline[i * 2] = centreU + radius * (float) Math.cos(angle);
            outline[i * 2 + 1] = centreV + radius * (float) Math.sin(angle);
        }
        return outline;
    }

    private void box(String name, float x0, float x1, float y0, float y1, float z0, float z1, String material) {
        prism(name, AXIS_Z, new float[] {x0, y0, x1, y0, x1, y1, x0, y1}, z0, z1, material);
    }

    private void prism(String name, int axis, float[] outline, float from, float to, String material) {
        int corners = outline.length / 2;
        float low = Math.min(from, to);
        float high = Math.max(from, to);
        boolean reversed = signedArea(outline) < 0f;
        float[][] lowLoop = new float[corners][3];
        float[][] highLoop = new float[corners][3];
        for (int i = 0; i < corners; i++) {
            int corner = reversed ? corners - 1 - i : i;
            float u = outline[corner * 2];
            float v = outline[corner * 2 + 1];
            if (axis == AXIS_X) {
                lowLoop[i] = new float[] {low, u, v};
                highLoop[i] = new float[] {high, u, v};
            } else {
                lowLoop[i] = new float[] {u, v, low};
                highLoop[i] = new float[] {u, v, high};
            }
        }
        loft(name, lowLoop, highLoop, material);
    }

    private void loft(String name, float[][] lowLoop, float[][] highLoop, String material) {
        int corners = lowLoop.length;
        obj.append("g ").append(name).append('\n');
        obj.append("usemtl ").append(material).append('\n');
        int lowBase = vertexCount + 1;
        for (float[] p : lowLoop) emitVertex(p);
        int highBase = lowBase + corners;
        for (float[] p : highLoop) emitVertex(p);
        vertexCount += corners * 2;
        groupCount++;

        // Caps, fanned identically to a convex polygon.
        for (int i = 1; i < corners - 1; i++) {
            emitFace(highBase, highBase + i, highBase + i + 1);
            emitFace(lowBase, lowBase + i + 1, lowBase + i);
        }
        // Sides, two triangles per edge.
        for (int i = 0; i < corners; i++) {
            int next = (i + 1) % corners;
            emitFace(highBase + i, lowBase + i, lowBase + next);
            emitFace(highBase + i, lowBase + next, highBase + next);
        }
    }

    private void emitVertex(float[] p) {
        obj.append("v ")
            .append(Float.toString(p[0])).append(' ')
            .append(Float.toString(p[1])).append(' ')
            .append(Float.toString(p[2])).append('\n');
    }

    private void emitFace(int a, int b, int c) {
        obj.append("f ").append(a).append(' ').append(b).append(' ').append(c).append('\n');
        faceCount++;
    }

    private static float signedArea(float[] outline) {
        float twiceArea = 0f;
        int corners = outline.length / 2;
        for (int i = 0; i < corners; i++) {
            int next = (i + 1) % corners;
            twiceArea += outline[i * 2] * outline[next * 2 + 1] - outline[next * 2] * outline[i * 2 + 1];
        }
        return twiceArea * 0.5f;
    }
}
