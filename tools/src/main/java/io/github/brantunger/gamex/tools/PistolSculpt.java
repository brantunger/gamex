package io.github.brantunger.gamex.tools;

import io.github.brantunger.gamex.weapon.PistolModel;

/**
 * Generates {@code viewmodel-pistol.obj} with {@code # @part body/slide} and {@code # @socket muzzle} referencing
 * canonical dimensions from {@link PistolModel}.
 */
public final class PistolSculpt {

    private static final String GUNMETAL = "gunmetal";
    private static final String GUNMETAL_TOP = "gunmetal_top";
    private static final String DARK_METAL = "dark_metal";
    private static final String STEEL = "steel";
    private static final String BORE = "bore";
    private static final String BRASS = "brass";
    private static final String SIGHT_DOT = "sight_dot";
    private static final String POLYMER = "polymer";
    private static final String POLYMER_DARK = "polymer_dark";
    private static final String STIPPLE = "stipple";

    private PistolSculpt() {}

    public static MeshBuilder build() {
        MeshBuilder b = new MeshBuilder()
            .comment("The first-person pistol of gamex.")
            .comment("Generated by :tools (PistolSculpt); edit the generator, not this file.")
            .comment("Gun space: barrel along -z, y up, x to the shooter's right.")
            .part("body", "root", 0f, 0f, 0f)
            .part("slide", "body", 0f, 0f, 0f)
            .socket("muzzle", "body", PistolModel.MUZZLE_X, PistolModel.MUZZLE_Y, PistolModel.MUZZLE_Z);

        buildSlide(b);
        buildFrame(b);
        buildGrip(b);
        return b;
    }

    private static void buildSlide(MeshBuilder b) {
        b.usePart("slide");
        b.prism("slide", GUNMETAL, MeshBuilder.AXIS_Z, new float[] {
            -0.0125f, 0f, 0.0125f, 0f, 0.014f, 0.002f, 0.014f, 0.017f, -0.014f, 0.017f, -0.014f, 0.002f
        }, -0.105f, 0.082f);
        b.prism("slide top", GUNMETAL_TOP, MeshBuilder.AXIS_Z, new float[] {
            -0.014f, 0.017f, 0.014f, 0.017f, 0.0125f, 0.0225f, 0.009f, 0.0262f, 0.005f, 0.0275f,
            -0.005f, 0.0275f, -0.009f, 0.0262f, -0.0125f, 0.0225f
        }, -0.105f, 0.082f);
        for (int i = 0; i < 7; i++) {
            float z = 0.034f + i * 0.0065f;
            b.box("slide serration " + i, DARK_METAL, -0.0147f, 0.0147f, 0.003f, 0.0165f, z, z + 0.003f);
        }
        for (int i = 0; i < 4; i++) {
            float z = -0.094f + i * 0.0065f;
            b.box("slide front serration " + i, DARK_METAL, -0.0147f, 0.0147f, 0.003f, 0.0165f, z, z + 0.003f);
        }
        b.box("slide top groove", DARK_METAL, -0.003f, 0.003f, 0.0270f, 0.0281f, -0.086f, 0.060f);
        b.prism("slide front sight", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            0.0275f, -0.102f, 0.0275f, -0.090f, 0.0345f, -0.090f, 0.0345f, -0.094f
        }, -0.0022f, 0.0022f);
        b.box("slide front sight bead", BRASS, -0.0013f, 0.0013f, 0.0305f, 0.0338f, -0.0900f, -0.0894f);
        b.box("slide rear sight base", DARK_METAL, -0.0105f, 0.0105f, 0.0275f, 0.0305f, 0.0655f, 0.0795f);
        b.box("slide rear sight left", DARK_METAL, -0.0105f, -0.0033f, 0.0305f, 0.0362f, 0.0655f, 0.0795f);
        b.box("slide rear sight right", DARK_METAL, 0.0033f, 0.0105f, 0.0305f, 0.0362f, 0.0655f, 0.0795f);
        b.box("slide rear sight dot left", SIGHT_DOT, -0.0083f, -0.0055f, 0.0320f, 0.0348f, 0.0795f, 0.0800f);
        b.box("slide rear sight dot right", SIGHT_DOT, 0.0055f, 0.0083f, 0.0320f, 0.0348f, 0.0795f, 0.0800f);
        b.box("slide ejection port", DARK_METAL, 0.006f, 0.0143f, 0.011f, 0.0172f, -0.030f, 0.004f);
        b.box("slide back plate", DARK_METAL, -0.006f, 0.006f, 0.005f, 0.019f, 0.082f, 0.0827f);
    }

    private static void buildFrame(MeshBuilder b) {
        b.usePart("body");
        b.prism("barrel", STEEL, MeshBuilder.AXIS_Z, ring(PistolModel.MUZZLE_X, PistolModel.MUZZLE_Y, 0.0078f, 8),
            -0.110f, 0.010f);
        b.prism("bore", BORE, MeshBuilder.AXIS_Z, ring(PistolModel.MUZZLE_X, PistolModel.MUZZLE_Y, 0.0046f, 8),
            PistolModel.MUZZLE_Z, -0.110f);
        b.prism("frame", POLYMER, MeshBuilder.AXIS_X, new float[] {
            0f, -0.092f, 0f, 0.082f, -0.018f, 0.082f, -0.018f, -0.080f, -0.009f, -0.092f
        }, -PistolModel.GRIP_BODY_HALF_WIDTH, PistolModel.GRIP_BODY_HALF_WIDTH);
        for (int i = 0; i < 3; i++) {
            float z = -0.078f + i * 0.012f;
            b.box("rail slot " + i, POLYMER_DARK, -0.009f, 0.009f, -0.0215f, -0.018f, z, z + 0.007f);
        }
        b.box("stop lever", DARK_METAL, -0.0148f, -PistolModel.GRIP_BODY_HALF_WIDTH, -0.008f, -0.003f,
            -0.036f, -0.006f);
        b.prism("magazine release", DARK_METAL, MeshBuilder.AXIS_X, ring(-0.027f, 0.027f, 0.0032f, 8),
            -PistolModel.FRAME_HALF_WIDTH, -PistolModel.GRIP_BODY_HALF_WIDTH);
        float[] outer = {-0.018f, -0.043f, -0.036f, -0.044f, -0.046f, -0.037f, -0.050f, -0.025f, -0.050f, 0.010f,
            -0.045f, 0.027f};
        float[] inner = {-0.018f, -0.039f, -0.034f, -0.040f, -0.042f, -0.034f, -0.0455f, -0.024f, -0.0455f, 0.009f,
            -0.041f, 0.024f};
        for (int i = 0; i < 5; i++) {
            b.prism("trigger guard " + i, POLYMER, MeshBuilder.AXIS_X, new float[] {
                inner[i * 2], inner[i * 2 + 1], inner[i * 2 + 2], inner[i * 2 + 3],
                outer[i * 2 + 2], outer[i * 2 + 3], outer[i * 2], outer[i * 2 + 1]
            }, -0.0055f, 0.0055f);
        }
        b.prism("trigger", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            -0.018f, -0.013f, -0.018f, -0.007f, -0.028f, -0.004f, -0.028f, -0.009f
        }, -0.003f, 0.003f);
        b.prism("trigger tip", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            -0.028f, -0.009f, -0.028f, -0.004f, -0.037f, -0.0055f, -0.037f, -0.0095f
        }, -0.003f, 0.003f);
        b.prism("hammer", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            0.002f, 0.082f, 0.014f, 0.084f, 0.019f, 0.090f, 0.017f, 0.095f, 0.008f, 0.092f, 0.002f, 0.088f
        }, -0.004f, 0.004f);
        b.prism("beavertail", POLYMER, MeshBuilder.AXIS_X, new float[] {
            -0.004f, 0.080f, -0.004f, 0.094f, -0.007f, 0.100f, -0.011f, 0.102f, -0.016f, 0.098f, -0.018f, 0.082f
        }, -PistolModel.BEAVERTAIL_HALF_WIDTH, PistolModel.BEAVERTAIL_HALF_WIDTH);
    }

    private static void buildGrip(MeshBuilder b) {
        b.usePart("body");
        b.prism("grip", POLYMER, MeshBuilder.AXIS_X, PistolModel.GRIP_OUTLINE,
            -PistolModel.GRIP_BODY_HALF_WIDTH, PistolModel.GRIP_BODY_HALF_WIDTH);
        b.prism("magazine plate", POLYMER_DARK, MeshBuilder.AXIS_X, new float[] {
            -0.105f, 0.046f, -0.105f, 0.113f, -0.112f, 0.115f, -0.112f, 0.048f
        }, -PistolModel.PLATE_HALF_WIDTH, PistolModel.PLATE_HALF_WIDTH);
        for (int row = 0; row < 11; row++) {
            float y = -0.030f - row * 0.0066f;
            for (int column = 0; column < 6; column++) {
                float z = PistolModel.frontStrap(y) + 0.008f + column * 0.0068f;
                String material = (row + column) % 2 == 0 ? STIPPLE : POLYMER_DARK;
                b.box("stipple left " + row + "/" + column, material,
                    -PistolModel.GRIP_HALF_WIDTH, -PistolModel.GRIP_BODY_HALF_WIDTH, y - 0.0036f, y, z, z + 0.0036f);
                b.box("stipple right " + row + "/" + column, material,
                    PistolModel.GRIP_BODY_HALF_WIDTH, PistolModel.GRIP_HALF_WIDTH, y - 0.0036f, y, z, z + 0.0036f);
            }
        }
    }

    private static float[] ring(float centreU, float centreV, float radius, int sides) {
        float[] outline = new float[sides * 2];
        for (int i = 0; i < sides; i++) {
            double angle = (i + 0.5) * 2.0 * Math.PI / sides;
            outline[i * 2] = centreU + radius * (float) Math.cos(angle);
            outline[i * 2 + 1] = centreV + radius * (float) Math.sin(angle);
        }
        return outline;
    }
}
