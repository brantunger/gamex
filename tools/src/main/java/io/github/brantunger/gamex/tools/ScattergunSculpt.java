package io.github.brantunger.gamex.tools;

import io.github.brantunger.gamex.weapon.PistolModel;
import io.github.brantunger.gamex.weapon.ScattergunModel;

/**
 * Generates {@code viewmodel-scattergun.obj} with {@code # @part body/pump} and {@code # @socket muzzle}. The rear
 * grip, trigger and rear receiver envelope match {@link PistolModel} so {@code viewmodel-hand.obj} fits cleanly with
 * zero glove penetration, while the heavy receiver, heatshield, side-saddle shells and ribbed pump extend ahead.
 */
public final class ScattergunSculpt {

    private static final String GUNMETAL = "gunmetal";
    private static final String GUNMETAL_TOP = "gunmetal_top";
    private static final String DARK_METAL = "dark_metal";
    private static final String STEEL = "steel";
    private static final String BORE = "bore";
    private static final String BRASS = "brass";
    private static final String SIGHT_DOT = "sight_dot";
    private static final String SIGHT_AMBER = "sight_amber";
    private static final String POLYMER = "polymer";
    private static final String POLYMER_DARK = "polymer_dark";
    private static final String STIPPLE = "stipple";
    private static final String SHELL_RED = "shell_red";
    private static final String HEATSHIELD = "heatshield";

    private ScattergunSculpt() {}

    public static MeshBuilder build() {
        MeshBuilder b = new MeshBuilder()
            .comment("The first-person Combat Scattergun of gamex.")
            .comment("Generated by :tools (ScattergunSculpt); edit the generator, not this file.")
            .comment("Gun space: barrel along -z, y up, x to the shooter's right.")
            .part("body", "root", 0f, 0f, 0f)
            .part("pump", "body", 0f, 0f, 0f)
            .socket("muzzle", "body", ScattergunModel.MUZZLE_X, ScattergunModel.MUZZLE_Y, ScattergunModel.MUZZLE_Z);

        buildGrip(b);
        buildReceiverAndBarrels(b);
        buildPump(b);
        return b;
    }

    private static void buildGrip(MeshBuilder b) {
        b.usePart("body");
        b.prism("grip", POLYMER, MeshBuilder.AXIS_X, PistolModel.GRIP_OUTLINE,
            -PistolModel.GRIP_BODY_HALF_WIDTH, PistolModel.GRIP_BODY_HALF_WIDTH);
        b.prism("magazine plate", POLYMER_DARK, MeshBuilder.AXIS_X, new float[] {
            -0.105f, 0.046f, -0.105f, 0.113f, -0.112f, 0.115f, -0.112f, 0.048f
        }, -PistolModel.PLATE_HALF_WIDTH, PistolModel.PLATE_HALF_WIDTH);
        for (int row = 0; row < 11; row++) {
            float y = -0.030f - row * 0.0066f;
            for (int column = 0; column < 6; column++) {
                float z = PistolModel.frontStrap(y) + 0.008f + column * 0.0068f;
                String material = (row + column) % 2 == 0 ? STIPPLE : POLYMER_DARK;
                b.box("stipple left " + row + "/" + column, material,
                    -PistolModel.GRIP_HALF_WIDTH, -PistolModel.GRIP_BODY_HALF_WIDTH, y - 0.0036f, y, z, z + 0.0036f);
                b.box("stipple right " + row + "/" + column, material,
                    PistolModel.GRIP_BODY_HALF_WIDTH, PistolModel.GRIP_HALF_WIDTH, y - 0.0036f, y, z, z + 0.0036f);
            }
        }
        b.prism("beavertail", POLYMER, MeshBuilder.AXIS_X, new float[] {
            -0.004f, 0.080f, -0.004f, 0.094f, -0.007f, 0.100f, -0.011f, 0.102f, -0.016f, 0.098f, -0.018f, 0.082f
        }, -PistolModel.BEAVERTAIL_HALF_WIDTH, PistolModel.BEAVERTAIL_HALF_WIDTH);

        float[] outer = {-0.018f, -0.043f, -0.036f, -0.044f, -0.046f, -0.037f, -0.050f, -0.025f, -0.050f, 0.010f,
            -0.045f, 0.027f};
        float[] inner = {-0.018f, -0.039f, -0.034f, -0.040f, -0.042f, -0.034f, -0.0455f, -0.024f, -0.0455f, 0.009f,
            -0.041f, 0.024f};
        for (int i = 0; i < 5; i++) {
            b.prism("trigger guard " + i, POLYMER_DARK, MeshBuilder.AXIS_X, new float[] {
                inner[i * 2], inner[i * 2 + 1], inner[i * 2 + 2], inner[i * 2 + 3],
                outer[i * 2 + 2], outer[i * 2 + 3], outer[i * 2], outer[i * 2 + 1]
            }, -0.0055f, 0.0055f);
        }
        b.prism("trigger", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            -0.018f, -0.013f, -0.018f, -0.007f, -0.028f, -0.004f, -0.028f, -0.009f
        }, -0.003f, 0.003f);
        b.prism("trigger tip", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            -0.028f, -0.009f, -0.028f, -0.004f, -0.037f, -0.0055f, -0.037f, -0.0095f
        }, -0.003f, 0.003f);
    }

    private static void buildReceiverAndBarrels(MeshBuilder b) {
        b.usePart("body");
        // Rear receiver strictly fits within PistolModel's grip/frame/slide envelope across z in [-0.048, 0.082].
        b.box("rear_receiver", GUNMETAL, -0.0128f, 0.0128f, -0.018f, 0.026f, -0.048f, 0.082f);
        b.prism("rear_receiver_top", GUNMETAL_TOP, MeshBuilder.AXIS_Z, new float[] {
            -0.0128f, 0.026f, 0.0128f, 0.026f, 0.0102f, 0.033f, -0.0102f, 0.033f
        }, -0.048f, 0.082f);

        // Tactical ghost-ring rear sight mounted clearly above hand height.
        b.box("rear_sight_base", DARK_METAL, -0.010f, 0.010f, 0.033f, 0.0365f, 0.056f, 0.074f);
        b.box("rear_sight_wing_l", DARK_METAL, -0.010f, -0.006f, 0.0365f, 0.045f, 0.056f, 0.074f);
        b.box("rear_sight_wing_r", DARK_METAL, 0.006f, 0.010f, 0.0365f, 0.045f, 0.056f, 0.074f);
        b.box("rear_sight_bridge", DARK_METAL, -0.008f, 0.008f, 0.045f, 0.0485f, 0.056f, 0.074f);
        b.box("rear_sight_dot_l", SIGHT_DOT, -0.009f, -0.0068f, 0.0385f, 0.0425f, 0.0740f, 0.0746f);
        b.box("rear_sight_dot_r", SIGHT_DOT, 0.0068f, 0.009f, 0.0385f, 0.0425f, 0.0740f, 0.0746f);

        // Heavy stepped forward receiver ahead of the hand/thumb region (z <= -0.048).
        b.box("forward_receiver", GUNMETAL, -0.0172f, 0.0172f, -0.020f, 0.0315f, -0.132f, -0.048f);
        b.prism("forward_receiver_top", GUNMETAL_TOP, MeshBuilder.AXIS_Z, new float[] {
            -0.0172f, 0.0315f, 0.0172f, 0.0315f, 0.0132f, 0.0365f, -0.0132f, 0.0365f
        }, -0.132f, -0.048f);
        b.box("ejection_port", DARK_METAL, 0.011f, 0.0176f, 0.011f, 0.025f, -0.112f, -0.062f);
        b.box("loading_gate", STEEL, -0.008f, 0.008f, -0.0210f, -0.0195f, -0.118f, -0.056f);

        // 3-shell side-saddle carrier mounted on the visible left flank (-X) ahead of the thumb.
        b.box("saddle_plate", DARK_METAL, -0.0196f, -0.0172f, -0.009f, 0.019f, -0.124f, -0.054f);
        for (int i = 0; i < 3; i++) {
            float z = -0.112f + i * 0.022f;
            b.box("saddle_clip_" + i, POLYMER_DARK, -0.0256f, -0.0196f, -0.001f, 0.009f, z - 0.0044f, z + 0.0044f);
            b.box("saddle_hull_" + i, SHELL_RED, -0.0250f, -0.0198f, -0.007f, 0.0185f, z - 0.0038f, z + 0.0038f);
            b.box("saddle_brass_" + i, BRASS, -0.0252f, -0.0197f, 0.0185f, 0.0245f, z - 0.0039f, z + 0.0039f);
        }

        // Heavy upper barrel, recessed bore, perforated heatshield and fiber-optic front sight.
        b.prism("barrel", STEEL, MeshBuilder.AXIS_Z, ring(ScattergunModel.MUZZLE_X, ScattergunModel.MUZZLE_Y, 0.0108f, 10),
            -0.275f, -0.132f);
        b.prism("bore", BORE, MeshBuilder.AXIS_Z, ring(ScattergunModel.MUZZLE_X, ScattergunModel.MUZZLE_Y, 0.0074f, 10),
            ScattergunModel.MUZZLE_Z, -0.275f);
        b.prism("heatshield", HEATSHIELD, MeshBuilder.AXIS_Z, new float[] {
            -0.0132f, 0.021f, 0.0132f, 0.021f, 0.0115f, 0.032f, 0.005f, 0.035f,
            -0.005f, 0.035f, -0.0115f, 0.032f
        }, -0.244f, -0.132f);
        for (int i = 0; i < 6; i++) {
            float z = -0.236f + i * 0.017f;
            b.box("heatshield_slot_" + i, DARK_METAL, -0.0065f, 0.0065f, 0.0342f, 0.0365f, z, z + 0.0085f);
        }
        b.prism("front_sight_ramp", DARK_METAL, MeshBuilder.AXIS_X, new float[] {
            0.030f, -0.270f, 0.030f, -0.254f, 0.0415f, -0.254f, 0.0415f, -0.260f
        }, -0.0032f, 0.0032f);
        b.box("front_sight_bead", SIGHT_AMBER, -0.0020f, 0.0020f, 0.0365f, 0.0405f, -0.254f, -0.2525f);

        // Underbarrel tubular magazine, brass endcap and front barrel clamp.
        b.prism("mag_tube", GUNMETAL, MeshBuilder.AXIS_Z, ring(0f, -0.003f, 0.0088f, 10),
            -0.260f, -0.048f);
        b.prism("mag_cap", BRASS, MeshBuilder.AXIS_Z, ring(0f, -0.003f, 0.0094f, 10),
            -0.267f, -0.260f);
        b.box("barrel_clamp", DARK_METAL, -0.0128f, 0.0128f, -0.0135f, 0.0295f, -0.252f, -0.238f);
    }

    private static void buildPump(MeshBuilder b) {
        b.usePart("pump");
        b.prism("pump_forend", POLYMER, MeshBuilder.AXIS_Z, new float[] {
            -0.0155f, -0.0215f, 0.0155f, -0.0215f, 0.0205f, -0.014f, 0.0205f, 0.0035f,
            0.0145f, 0.0095f, -0.0145f, 0.0095f, -0.0205f, 0.0035f, -0.0205f, -0.014f
        }, -0.222f, -0.132f);
        b.box("pump_collar_front", DARK_METAL, -0.018f, 0.018f, -0.019f, 0.007f, -0.228f, -0.222f);
        b.box("pump_collar_rear", DARK_METAL, -0.018f, 0.018f, -0.019f, 0.007f, -0.132f, -0.126f);
        for (int i = 0; i < 6; i++) {
            float z = -0.214f + i * 0.0135f;
            b.box("pump_rib_" + i, POLYMER_DARK, -0.0222f, 0.0222f, -0.0230f, 0.0045f, z, z + 0.0065f);
        }
    }

    private static float[] ring(float centreU, float centreV, float radius, int sides) {
        float[] outline = new float[sides * 2];
        for (int i = 0; i < sides; i++) {
            double angle = (i + 0.5) * 2.0 * Math.PI / sides;
            outline[i * 2] = centreU + radius * (float) Math.cos(angle);
            outline[i * 2 + 1] = centreV + radius * (float) Math.sin(angle);
        }
        return outline;
    }
}
