package io.github.brantunger.gamex.tools;

import io.github.brantunger.gamex.weapon.PistolModel;
import io.github.brantunger.gamex.weapon.ScattergunModel;

/**
 * Generates {@code viewmodel-scattergun.obj} with {@code # @part body/pump} and {@code # @socket muzzle} styled as a
 * shortened TF2 Scout-inspired double-barrel drum Scattergun. The rear grip, trigger and rear receiver envelope match
 * {@link PistolModel} so {@code viewmodel-hand.obj} fits cleanly with zero glove penetration, while the transverse drum
 * receiver, stubby side-by-side barrels, walnut wood furniture, and compact lever-action forend sit ahead.
 */
public final class ScattergunSculpt {

    private static final String GUNMETAL = "gunmetal";
    private static final String GUNMETAL_TOP = "gunmetal_top";
    private static final String DARK_METAL = "dark_metal";
    private static final String STEEL = "steel";
    private static final String BORE = "bore";
    private static final String BRASS = "brass";
    private static final String SIGHT_DOT = "sight_dot";
    private static final String WOOD = "wood";
    private static final String WOOD_DARK = "wood_dark";

    private ScattergunSculpt() {}

    public static MeshBuilder build() {
        MeshBuilder b = new MeshBuilder()
            .comment("The first-person shortened double-barrel drum Combat Scattergun of gamex.")
            .comment("Generated by :tools (ScattergunSculpt); edit the generator, not this file.")
            .comment("Gun space: barrels along -z, y up, x to the shooter's right.")
            .part("body", "root", 0f, 0f, 0f)
            .part("pump", "body", 0f, 0f, 0f)
            .socket("muzzle", "body", ScattergunModel.MUZZLE_X, ScattergunModel.MUZZLE_Y, ScattergunModel.MUZZLE_Z);

        ViewmodelGrip.build(b, WOOD, WOOD_DARK, WOOD_DARK, DARK_METAL);
        buildReceiverAndBarrels(b);
        buildPump(b);
        return b;
    }

    private static void buildReceiverAndBarrels(MeshBuilder b) {
        b.usePart("body");
        // Rear receiver strictly fits within PistolModel's grip/frame/slide envelope across z in [-0.048, 0.082].
        b.box("rear_receiver", GUNMETAL, -0.0128f, 0.0128f, -0.018f, 0.026f, -0.048f, 0.082f);
        b.prism("rear_receiver_top", GUNMETAL_TOP, MeshBuilder.AXIS_Z, new float[] {
            -0.0128f, 0.026f, 0.0128f, 0.026f, 0.0102f, 0.033f, -0.0102f, 0.033f
        }, -0.048f, 0.082f);

        // Low-profile notch rear sight clear above hand height.
        b.box("rear_sight_l", DARK_METAL, -0.0095f, -0.0032f, 0.033f, 0.040f, 0.058f, 0.074f);
        b.box("rear_sight_r", DARK_METAL, 0.0032f, 0.0095f, 0.033f, 0.040f, 0.058f, 0.074f);
        b.box("rear_sight_dot_l", SIGHT_DOT, -0.0080f, -0.0046f, 0.0345f, 0.0385f, 0.0740f, 0.0746f);
        b.box("rear_sight_dot_r", SIGHT_DOT, 0.0046f, 0.0080f, 0.0345f, 0.0385f, 0.0740f, 0.0746f);

        // Iconic transverse cylindrical drum receiver ahead of the hand/thumb region (z <= -0.057).
        float drumY = 0.003f;
        float drumZ = -0.086f;
        b.prism("drum_receiver", GUNMETAL, MeshBuilder.AXIS_X, ViewmodelGrip.ring(drumY, drumZ, 0.029f, 12),
            -0.025f, 0.025f);
        b.prism("drum_cap_l", DARK_METAL, MeshBuilder.AXIS_X, ViewmodelGrip.ring(drumY, drumZ, 0.022f, 12),
            -0.0275f, -0.025f);
        b.prism("drum_cap_r", DARK_METAL, MeshBuilder.AXIS_X, ViewmodelGrip.ring(drumY, drumZ, 0.022f, 12),
            0.025f, 0.0275f);
        b.prism("drum_pin_l", BRASS, MeshBuilder.AXIS_X, ViewmodelGrip.ring(drumY, drumZ, 0.0065f, 8),
            -0.0295f, -0.0275f);
        b.prism("drum_pin_r", BRASS, MeshBuilder.AXIS_X, ViewmodelGrip.ring(drumY, drumZ, 0.0065f, 8),
            0.0275f, 0.0295f);

        // Upper receiver spine bridging rear receiver to twin barrels.
        b.box("receiver_spine", GUNMETAL_TOP, -0.015f, 0.015f, 0.022f, 0.035f, -0.118f, -0.048f);
        b.box("ejection_port", DARK_METAL, 0.013f, 0.016f, 0.023f, 0.032f, -0.104f, -0.068f);

        // Shortened twin side-by-side sawed-off barrels, recessed bores, center rib, brass bead and muzzle clamp.
        b.prism("barrel_left", STEEL, MeshBuilder.AXIS_Z,
            ViewmodelGrip.ring(-0.0112f, ScattergunModel.MUZZLE_Y, 0.0106f, 10), -0.194f, -0.110f);
        b.prism("bore_left", BORE, MeshBuilder.AXIS_Z,
            ViewmodelGrip.ring(-0.0112f, ScattergunModel.MUZZLE_Y, 0.0074f, 10),
            ScattergunModel.MUZZLE_Z, -0.194f);
        b.prism("barrel_right", STEEL, MeshBuilder.AXIS_Z,
            ViewmodelGrip.ring(0.0112f, ScattergunModel.MUZZLE_Y, 0.0106f, 10), -0.194f, -0.110f);
        b.prism("bore_right", BORE, MeshBuilder.AXIS_Z,
            ViewmodelGrip.ring(0.0112f, ScattergunModel.MUZZLE_Y, 0.0074f, 10),
            ScattergunModel.MUZZLE_Z, -0.194f);

        b.box("barrel_rib", DARK_METAL, -0.0035f, 0.0035f, 0.025f, 0.0315f, -0.190f, -0.114f);
        b.box("front_sight_bead", BRASS, -0.0020f, 0.0020f, 0.0315f, 0.0365f, -0.188f, -0.182f);
        b.box("muzzle_band", DARK_METAL, -0.0228f, 0.0228f, 0.010f, 0.028f, -0.178f, -0.166f);
        b.box("under_lug", GUNMETAL, -0.0055f, 0.0055f, -0.004f, 0.010f, -0.184f, -0.112f);
    }

    private static void buildPump(MeshBuilder b) {
        b.usePart("pump");
        // Compact walnut wood handguard + metallic lever-action cocking loop staying clear of hand at full travel.
        b.prism("pump_forend", WOOD, MeshBuilder.AXIS_Z, new float[] {
            -0.014f, -0.016f, 0.014f, -0.016f, 0.018f, -0.008f, 0.018f, 0.004f,
            0.013f, 0.009f, -0.013f, 0.009f, -0.018f, 0.004f, -0.018f, -0.008f
        }, -0.178f, -0.120f);
        for (int i = 0; i < 3; i++) {
            float z = -0.170f + i * 0.016f;
            b.box("pump_rib_" + i, WOOD_DARK, -0.0192f, 0.0192f, -0.0170f, 0.001f, z, z + 0.006f);
        }
        b.box("lever_arm_f", STEEL, -0.0045f, 0.0045f, -0.032f, -0.016f, -0.156f, -0.148f);
        b.box("lever_loop_b", DARK_METAL, -0.0050f, 0.0050f, -0.034f, -0.026f, -0.156f, -0.116f);
        b.box("lever_arm_r", STEEL, -0.0045f, 0.0045f, -0.032f, -0.016f, -0.124f, -0.116f);
    }
}
