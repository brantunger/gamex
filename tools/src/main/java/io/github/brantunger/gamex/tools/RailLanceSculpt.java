package io.github.brantunger.gamex.tools;

import io.github.brantunger.gamex.weapon.PistolModel;
import io.github.brantunger.gamex.weapon.RailLanceModel;

/**
 * Generates {@code viewmodel-raillance.obj} with {@code # @part body/bolt}, {@code # @socket muzzle}, and
 * {@code # @accent rail_core}. The rear grip envelope matches {@link PistolModel} so {@code viewmodel-hand.obj} fits
 * cleanly with zero glove penetration, while the twin electromagnetic rails, copper coils, glowing capacitor ribs,
 * elevated rangefinder optic, and magnetic breech sled extend forward.
 */
public final class RailLanceSculpt {

    private static final String GUNMETAL = "gunmetal";
    private static final String GUNMETAL_TOP = "gunmetal_top";
    private static final String DARK_METAL = "dark_metal";
    private static final String STEEL = "steel";
    private static final String BORE = "bore";
    private static final String POLYMER = "polymer";
    private static final String POLYMER_DARK = "polymer_dark";
    private static final String STIPPLE = "stipple";
    private static final String SIGHT_DOT = "sight_dot";
    private static final String OPTIC_GLASS = "optic_glass";
    private static final String RAIL_COPPER = "rail_copper";
    private static final String RAIL_CORE = "rail_core";

    private RailLanceSculpt() {}

    public static MeshBuilder build() {
        MeshBuilder b = new MeshBuilder()
            .comment("The first-person Slot 3 Rail Lance of gamex.")
            .comment("Generated by :tools (RailLanceSculpt); edit the generator, not this file.")
            .comment("Gun space: rails along -z, y up, x to the shooter's right.")
            .accent(RAIL_CORE)
            .part("body", "root", 0f, 0f, 0f)
            .part("bolt", "body", 0f, 0f, 0f)
            .socket("muzzle", "body", RailLanceModel.MUZZLE_X, RailLanceModel.MUZZLE_Y, RailLanceModel.MUZZLE_Z);

        ViewmodelGrip.build(b, POLYMER, POLYMER_DARK, STIPPLE, DARK_METAL);
        buildChassisOpticAndRails(b);
        buildBolt(b);
        return b;
    }

    private static void buildChassisOpticAndRails(MeshBuilder b) {
        b.usePart("body");
        // Rear receiver strictly fits within PistolModel's grip/frame/slide envelope across z in [-0.048, 0.082].
        b.box("rear_receiver", GUNMETAL, -0.0128f, 0.0128f, -0.018f, 0.026f, -0.048f, 0.082f);
        b.prism("rear_receiver_top", GUNMETAL_TOP, MeshBuilder.AXIS_Z, new float[] {
            -0.0128f, 0.026f, 0.0128f, 0.026f, 0.0102f, 0.033f, -0.0102f, 0.033f
        }, -0.048f, 0.082f);
        b.box("rear_sight_pip", SIGHT_DOT, -0.0020f, 0.0020f, 0.0330f, 0.0365f, 0.068f, 0.074f);

        // Elevated rangefinder optic mounted cleanly above grip/hand height (y >= 0.0335).
        b.box("optic_rail_base", DARK_METAL, -0.0075f, 0.0075f, 0.0285f, 0.0365f, -0.135f, -0.010f);
        b.box("optic_riser_f", DARK_METAL, -0.0068f, 0.0068f, 0.0365f, 0.0410f, -0.120f, -0.095f);
        b.box("optic_riser_r", DARK_METAL, -0.0068f, 0.0068f, 0.0365f, 0.0410f, -0.042f, -0.016f);
        b.prism("optic_tube", GUNMETAL_TOP, MeshBuilder.AXIS_Z, ViewmodelGrip.ring(0f, 0.048f, 0.0110f, 8),
            -0.138f, 0.008f);
        b.box("optic_hood_f", DARK_METAL, -0.0118f, 0.0118f, 0.041f, 0.060f, -0.146f, -0.138f);
        b.prism("optic_lens_f", OPTIC_GLASS, MeshBuilder.AXIS_Z, ViewmodelGrip.ring(0f, 0.048f, 0.0082f, 8),
            -0.148f, -0.146f);
        b.prism("optic_lens_r", OPTIC_GLASS, MeshBuilder.AXIS_Z, ViewmodelGrip.ring(0f, 0.048f, 0.0082f, 8),
            0.008f, 0.011f);
        b.box("optic_glow_pip", RAIL_CORE, -0.0116f, -0.0090f, 0.046f, 0.050f, -0.105f, -0.055f);

        // Heavy forward capacitor chassis strictly ahead of the hand/thumb envelope (z <= -0.052).
        b.box("forward_chassis", GUNMETAL, -0.0180f, 0.0180f, -0.020f, 0.0285f, -0.152f, -0.052f);
        b.box("under_capacitor", POLYMER_DARK, -0.0142f, 0.0142f, -0.036f, -0.020f, -0.215f, -0.056f);
        for (int i = 0; i < 4; i++) {
            float z = -0.138f + i * 0.022f;
            b.box("cap_cell_l_" + i, RAIL_CORE, -0.0206f, -0.0180f, -0.009f, 0.004f, z, z + 0.011f);
            b.box("cap_cell_r_" + i, RAIL_CORE, 0.0180f, 0.0206f, -0.009f, 0.004f, z, z + 0.011f);
        }

        // Twin parallel electromagnetic rails + lower stabilizer + glowing central plasma core.
        b.box("rail_left", STEEL, -0.0175f, -0.0068f, 0.006f, 0.026f, -0.295f, -0.152f);
        b.box("rail_right", STEEL, 0.0068f, 0.0175f, 0.006f, 0.026f, -0.295f, -0.152f);
        b.box("rail_under", DARK_METAL, -0.0125f, 0.0125f, -0.013f, 0.002f, -0.282f, -0.152f);
        b.box("rail_core_channel", RAIL_CORE, -0.0042f, 0.0042f, 0.008f, 0.022f, -0.285f, -0.152f);
        b.box("muzzle_aperture", BORE, -0.0052f, 0.0052f, 0.010f, 0.024f, -0.295f, -0.285f);
        b.box("muzzle_cap_l", DARK_METAL, -0.0195f, -0.0058f, 0.004f, 0.0285f, -0.298f, -0.284f);
        b.box("muzzle_cap_r", DARK_METAL, 0.0058f, 0.0195f, 0.004f, 0.0285f, -0.298f, -0.284f);

        // Exposed copper induction coils wrapping the twin rails.
        for (int i = 0; i < 4; i++) {
            float z = -0.268f + i * 0.028f;
            b.box("coil_l_" + i, RAIL_COPPER, -0.0195f, -0.0175f, 0.008f, 0.024f, z, z + 0.012f);
            b.box("coil_r_" + i, RAIL_COPPER, 0.0175f, 0.0195f, 0.008f, 0.024f, z, z + 0.012f);
        }
    }

    private static void buildBolt(MeshBuilder b) {
        b.usePart("bolt");
        // Kept strictly ahead of z = -0.056 even at full BOLT_TRAVEL (+0.042) so the glove never clips.
        b.box("bolt_carriage", STEEL, -0.0195f, 0.0195f, 0.008f, 0.032f, -0.142f, -0.102f);
        b.box("bolt_handle_l", DARK_METAL, -0.0265f, -0.0195f, 0.015f, 0.025f, -0.130f, -0.110f);
        b.box("bolt_accent_l", RAIL_CORE, -0.0212f, -0.0195f, 0.016f, 0.024f, -0.140f, -0.132f);
    }
}
